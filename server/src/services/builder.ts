import fs from 'fs';
import path from 'path';
import { CardMeta, MergedEntry, WorldbookMeta } from '../types';
import { POS_MAP } from '../config';

/**
 * 根据元数据与条目配置，组装符合 SillyTavern Character Card Spec V3 的卡片对象
 */
export function buildTavernV3Card(
  meta: CardMeta,
  entriesConfig: MergedEntry[]
): Record<string, unknown> {
  const nowStr = new Date().toISOString().replace(/\.\d{3}Z$/, 'Z');

  const cardName = meta.cardName || 'Unnamed_Card';
  const cardDescription = meta.cardDescription || '';
  const firstMes = meta.firstMes || '';
  const tagsRaw = meta.tags || '';
  const creator = meta.creator || 'Antigravity';
  const version = meta.characterVersion || '1.0.0';

  // 解析 tags：按中英文逗号拆分
  const tagsList: string[] = tagsRaw.trim()
    ? tagsRaw
        .split(/[,，]+/)
        .map((t) => t.trim())
        .filter(Boolean)
    : [];

  const entries: Record<string, unknown>[] = [];
  let entryIdx = 0;

  for (const config of entriesConfig) {
    // 跳过禁用的或无效的条目
    if (!config.enabled || !config.isValid) continue;

    // 读取文件内容
    let contentStr = '';
    try {
      const raw = fs.readFileSync(config.fullPath, 'utf-8');
      if (config.filename.endsWith('.json')) {
        try {
          const dataObj = JSON.parse(raw);
          contentStr = JSON.stringify(dataObj, null, 2);
        } catch {
          contentStr = raw;
        }
      } else {
        contentStr = raw;
      }
    } catch (e) {
      console.warn(`[Warning] Cannot read entry file ${config.fullPath}:`, e);
      continue;
    }

    const isConstant = config.lightType === 'constant';
    const extPos = POS_MAP[config.position] ?? 0;

    // 触发词按中英文逗号拆分成列表：不管是蓝灯还是绿灯均保留默认触发词
    const baseName = path.basename(config.filename, path.extname(config.filename));
    const triggerKeyRaw = config.triggerKey?.trim() ? config.triggerKey.trim() : baseName;
    let keysList: string[] = triggerKeyRaw
      .split(/[,，]+/)
      .map((k) => k.trim())
      .filter(Boolean);
    if (keysList.length === 0) {
      keysList = [baseName];
    }

    const entryDict: Record<string, unknown> = {
      id: entryIdx,
      keys: keysList,
      secondary_keys: [],
      comment: triggerKeyRaw || config.filename,
      content: contentStr,
      constant: isConstant,
      selective: !isConstant,
      insertion_order: 100,
      enabled: true,
      position: config.position,
      use_regex: false,
      extensions: {
        position: extPos,
        exclude_recursion: true,
        prevent_recursion: true,
        delay_until_recursion: false,
        display_index: entryIdx,
        probability: 100,
        useProbability: true,
        depth: 4,
        selectiveLogic: 0,
        group: '',
        group_override: false,
        group_weight: 100,
        scan_depth: null,
        match_whole_words: null,
        use_group_scoring: false,
        case_sensitive: null,
        automation_id: '',
        role: 0,
        vectorized: false,
        sticky: 0,
        cooldown: 0,
        delay: 0,
        match_persona_description: false,
        match_character_description: false,
        match_character_personality: false,
        match_character_depth_prompt: false,
        match_scenario: false,
        match_creator_notes: false,
        triggers: [],
        ignore_budget: false,
      },
    };

    entries.push(entryDict);
    entryIdx++;
  }

  const cardData: Record<string, unknown> = {
    spec: 'chara_card_v3',
    spec_version: '3.0',
    name: cardName,
    description: cardDescription,
    personality: '',
    scenario: '',
    first_mes: firstMes,
    mes_example: '',
    creator_notes: 'Generated by CardPacker Pro',
    system_prompt: '',
    post_history_instructions: '',
    tags: tagsList,
    creator,
    character_version: version,
    alternate_greetings: [],
    avatar: 'none',
    create_date: nowStr,
    talkativeness: '0.5',
    fav: false,
    data: {
      name: cardName,
      description: cardDescription,
      personality: '',
      scenario: '',
      first_mes: firstMes,
      mes_example: '',
      creator_notes: 'Generated by CardPacker Pro',
      system_prompt: '',
      post_history_instructions: '',
      tags: tagsList,
      creator,
      character_version: version,
      alternate_greetings: [],
      extensions: {
        talkativeness: '0.5',
        fav: false,
        world: cardName,
        depth_prompt: {
          prompt: '',
          depth: 4,
          role: 'system',
        },
        regex_scripts: [],
        tavern_helper: [],
      },
      character_book: {
        name: cardName,
        entries,
      },
    },
  };

  return cardData;
}

/**
 * 根据条目配置直接组装符合 SillyTavern 规范的独立世界书（Lorebook/World Info）对象
 * 没有角色卡相关的设定/开场白描述
 */
